// Network is the shared bridge network the gateway reaches apps on.
const Network = "hub"

const (
	labelProject = "com.docker.compose.project"
	labelService = "com.docker.compose.service"
)

type Options struct {
	// OverrideDir holds the generated compose override files.
	OverrideDir string
	// AppURL returns the browser URL of an app, e.g. http://notes.hub.localhost:7000.
	AppURL func(id string) string
	// CoreURL is the browser URL of the shell, e.g. http://hub.localhost:7000.
	CoreURL string
}

type Driver struct {
	cli  *client.Client
	opts Options
}

var _ runtime.Driver = (*Driver)(nil)

func New(opts Options) (*Driver, error) {
	cli, err := client.New(client.FromEnv)
	if err != nil {
		return nil, err
	}
	return &Driver{cli: cli, opts: opts}, nil
}

func (d *Driver) Close() error { return d.cli.Close() }

func (d *Driver) Prepare(ctx context.Context) error {
	if _, err := d.cli.Ping(ctx, client.PingOptions{}); err != nil {
		return fmt.Errorf("cannot reach Docker (is the engine running? try `sudo systemctl start docker`): %w", err)
	}
	if _, err := exec.LookPath("docker"); err != nil {
		return fmt.Errorf("docker CLI not found on PATH: %w", err)
	}
	_, err := d.cli.NetworkInspect(ctx, Network, client.NetworkInspectOptions{})
	if err == nil {
		return nil
	}
	if !cerrdefs.IsNotFound(err) {
		return fmt.Errorf("inspect network %q: %w", Network, err)
	}
	_, err = d.cli.NetworkCreate(ctx, Network, client.NetworkCreateOptions{
		Driver: "bridge",
		Labels: map[string]string{runtime.LabelManaged: "true"},
	})
	if err != nil && !cerrdefs.IsConflict(err) {
		return fmt.Errorf("create network %q: %w", Network, err)
	}
	return nil
}

// override is the compose file the core layers over the app's own: it joins
// the routed service to the hub network and injects labels + env.
func (d *Driver) override(in runtime.Instance) ([]byte, error) {
	id := in.App.ID
	svc := map[string]any{
		// Listing networks replaces the implicit default, so keep it explicitly
		// for the app's own services (e.g. its database).
		"networks": map[string]any{"default": map[string]any{}, Network: map[string]any{}},
		"labels": map[string]string{
			runtime.LabelAppID:   id,
			runtime.LabelManaged: "true",
		},
		"environment": map[string]string{
			"HUB_APP_ID":   id,
			"HUB_APP_URL":  d.opts.AppURL(id),
			"HUB_CORE_URL": d.opts.CoreURL,
		},
	}
	return yaml.Marshal(map[string]any{
		"services": map[string]any{in.App.Runtime.Service: svc},
		"networks": map[string]any{Network: map[string]any{"external": true, "name": Network}},
	})
}

func (d *Driver) writeOverride(in runtime.Instance) (string, error) {
	data, err := d.override(in)
	if err != nil {
		return "", err
	}
	if err := os.MkdirAll(d.opts.OverrideDir, 0o755); err != nil {
		return "", err
	}
	path := filepath.Join(d.opts.OverrideDir, in.Project+".override.yaml")
	return path, os.WriteFile(path, append([]byte("# Generated by hub core — do not edit.\n"), data...), 0o644)
}

// ComposeError carries the CLI output of a failed compose command.
type ComposeError struct {
	Args   []string
	Output string
	Err    error
}

func (e *ComposeError) Error() string {
	return fmt.Sprintf("docker %s: %v\n%s", strings.Join(e.Args, " "), e.Err, e.Output)
}

func (e *ComposeError) Unwrap() error { return e.Err }

func (d *Driver) compose(ctx context.Context, in runtime.Instance, args ...string) error {
	override, err := d.writeOverride(in)
	if err != nil {
		return err
	}
	full := append([]string{
		"compose", "--ansi", "never", "--progress", "plain",
		"-p", in.Project,
		"--project-directory", in.App.Dir,
		"-f", in.App.ComposePath(), "-f", override,
	}, args...)
	cmd := exec.CommandContext(ctx, "docker", full...)
	cmd.Dir = in.App.Dir
	// On cancel, let compose stop gracefully instead of killing it mid-way.
	cmd.Cancel = func() error { return cmd.Process.Signal(os.Interrupt) }
	cmd.WaitDelay = 30 * time.Second
	var out bytes.Buffer
	cmd.Stdout, cmd.Stderr = &out, &out
	if err := cmd.Run(); err != nil {
		return &ComposeError{Args: full, Output: lastLines(out.String(), 40), Err: err}
	}
	return nil
}

func lastLines(s string, n int) string {
	lines := strings.Split(strings.TrimRight(s, "\n"), "\n")
	if len(lines) > n {
		lines = append([]string{"…"}, lines[len(lines)-n:]...)
	}
	return strings.Join(lines, "\n")
}

func (d *Driver) Start(ctx context.Context, in runtime.Instance, opts runtime.StartOptions) error {
	args := []string{"up", "--detach", "--remove-orphans"}
	if opts.Build {
		args = append(args, "--build")
	}
	return d.compose(ctx, in, args...)
}

func (d *Driver) Stop(ctx context.Context, in runtime.Instance, opts runtime.StopOptions) error {
	args := []string{"down", "--remove-orphans"}
	if opts.RemoveVolumes {
		args = append(args, "--volumes")
	}
	return d.compose(ctx, in, args...)
}

func filters(kv ...string) client.Filters {
	f := make(client.Filters)
	for i := 0; i+1 < len(kv); i += 2 {
		f.Add(kv[i], kv[i+1])
	}
	return f
}

func (d *Driver) Status(ctx context.Context, in runtime.Instance) (runtime.Status, error) {
	res, err := d.cli.ContainerList(ctx, client.ContainerListOptions{
		All: true,
		Filters: filters(
			"label", labelProject+"="+in.Project,
			"label", labelService+"="+in.App.Runtime.Service,
		),
	})
	if err != nil {
		return runtime.Status{}, err
	}
	var st runtime.Status
	for _, c := range res.Items {
		st.State = string(c.State)
		if c.State != container.StateRunning {
			continue
		}
		st.Running = true
		if c.NetworkSettings != nil {
			if ep := c.NetworkSettings.Networks[Network]; ep != nil && ep.IPAddress.IsValid() {
				st.Addr = net.JoinHostPort(ep.IPAddress.String(), strconv.Itoa(in.App.Runtime.Port))
			}
		}
		break
	}
	return st, nil
}

func (d *Driver) Running(ctx context.Context) ([]runtime.RunningInstance, error) {
	res, err := d.cli.ContainerList(ctx, client.ContainerListOptions{
		Filters: filters("label", runtime.LabelManaged+"=true", "status", "running"),
	})
	if err != nil {
		return nil, err
	}
	seen := map[runtime.RunningInstance]bool{}
	var out []runtime.RunningInstance
	for _, c := range res.Items {
		ri := runtime.RunningInstance{AppID: c.Labels[runtime.LabelAppID], Project: c.Labels[labelProject]}
		if ri.AppID != "" && !seen[ri] {
			seen[ri] = true
			out = append(out, ri)
		}
	}
	return out, nil
}

func (d *Driver) Events(ctx context.Context) (<-chan runtime.Event, <-chan error) {
	res := d.cli.Events(ctx, client.EventsListOptions{
		Filters: filters(
			"type", string(events.ContainerEventType),
			"label", runtime.LabelManaged+"=true",
			"event", string(events.ActionStart),
			"event", string(events.ActionDie),
		),
	})
	out := make(chan runtime.Event)
	go func() {
		defer close(out)
		for {
			select {
			case <-ctx.Done():
				return
			case msg, ok := <-res.Messages:
				if !ok {
					return
				}
				a := msg.Actor.Attributes
				ev := runtime.Event{
					AppID:    a[runtime.LabelAppID],
					Project:  a[labelProject],
					Service:  a[labelService],
					ExitCode: a["exitCode"],
				}
				switch msg.Action {
				case events.ActionStart:
					ev.Kind = runtime.EventStarted
				case events.ActionDie:
					ev.Kind = runtime.EventDied
				default:
					continue
				}
				select {
				case out <- ev:
				case <-ctx.Done():
					return
				}
			}
		}
	}()
	return out, res.Err
}

func (d *Driver) Logs(ctx context.Context, project string, tail int, follow bool) (<-chan runtime.LogLine, error) {
	res, err := d.cli.ContainerList(ctx, client.ContainerListOptions{
		All:     true,
		Filters: filters("label", labelProject+"="+project),
	})
	if err != nil {
		return nil, err
	}
	tailArg := "all"
	if tail > 0 {
		tailArg = strconv.Itoa(tail)
	}
	out := make(chan runtime.LogLine, 64)
	var wg sync.WaitGroup
	for _, c := range res.Items {
		insp, err := d.cli.ContainerInspect(ctx, c.ID, client.ContainerInspectOptions{})
		if err != nil {
			return nil, err
		}
		rc, err := d.cli.ContainerLogs(ctx, c.ID, client.ContainerLogsOptions{
			ShowStdout: true, ShowStderr: true, Follow: follow, Tail: tailArg,
		})
		if err != nil {
			return nil, err
		}
		service := c.Labels[labelService]
		tty := insp.Container.Config != nil && insp.Container.Config.Tty
		wg.Go(func() {
			defer rc.Close()
			pump(ctx, rc, tty, service, out)
		})
	}
	go func() { wg.Wait(); close(out) }()
	return out, nil
}

// pump splits a container log stream into lines. Without a TTY the stream is
// multiplexed (stdout/stderr frames) and needs stdcopy.
func pump(ctx context.Context, rc io.Reader, tty bool, service string, out chan<- runtime.LogLine) {
	scan := func(r io.Reader, stream string) {
		s := bufio.NewScanner(r)
		s.Buffer(make([]byte, 64*1024), 1024*1024)
		for s.Scan() {
			select {
			case out <- runtime.LogLine{Service: service, Stream: stream, Text: s.Text()}:
			case <-ctx.Done():
				return
			}
		}
	}
	if tty {
		scan(rc, "stdout")
		return
	}
	or, ow := io.Pipe()
	er, ew := io.Pipe()
	var wg sync.WaitGroup
	// Closing a reader when its scanner stops makes StdCopy's writes fail, so
	// StdCopy can never block on a stream nobody reads.
	wg.Go(func() { defer or.Close(); scan(or, "stdout") })
	wg.Go(func() { defer er.Close(); scan(er, "stderr") })
	_, err := stdcopy.StdCopy(ow, ew, rc)
	ow.CloseWithError(err)
	ew.CloseWithError(err)
	wg.Wait()
}
