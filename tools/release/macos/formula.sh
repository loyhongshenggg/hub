#!/usr/bin/env bash
# Writes Formula/<NAME>.rb for a built macOS release (Homebrew tap = this repo).
# Usage: tools/release/macos/formula.sh <release> <version>   (after build.sh)
set -euo pipefail
root="$(cd "$(dirname "$0")/../../.." && pwd)"
cd "$root"
rel="${1:?}" version="${2:?}"
# shellcheck source=/dev/null
. "releases/$rel.env"
repo="${GITHUB_REPOSITORY:-${RELEASE_REPO:?set RELEASE_REPO}}"
out="dist/release/$NAME"
sha() { sha256sum "$out/$NAME-macos-$1.tar.gz" | cut -d' ' -f1; }
class="$(echo "$NAME" | sed -E 's/(^|-)([a-z])/\U\2/g')"
base="https://github.com/$repo/releases/download/$NAME-v$version"
mkdir -p Formula
cat >"Formula/$NAME.rb" <<RB
# Generated by tools/release/macos/formula.sh for $NAME-v$version — don't edit by hand.
class $class < Formula
  desc "$TITLE, running on the hub (native, no Docker)"
  homepage "https://github.com/$repo"
  version "$version"

  on_arm do
    url "$base/$NAME-macos-arm64.tar.gz"
    sha256 "$(sha arm64)"
  end
  on_intel do
    url "$base/$NAME-macos-amd64.tar.gz"
    sha256 "$(sha amd64)"
  end

  depends_on :macos
  depends_on "poppler"
  depends_on "tesseract"

  def install
    libexec.install Dir["*"]
    bin.install_symlink libexec/"$NAME"
  end

  def caveats
    <<~EOS
      Open $TITLE with: $NAME
      The first run adds $TITLE to ~/Applications and the Dock. Needs Google Chrome or Microsoft Edge.
      Updating from 0.2.2 or older: run $NAME once so the Dock icon follows future updates.
    EOS
  end

  test do
    assert_match "$version", shell_output("#{libexec}/bin/hub version 2>&1; cat #{libexec}/release.env")
  end
end
RB
echo "wrote Formula/$NAME.rb"
